"""menu/player: one player, in the friends icon's colours. Bedrock shows it in place of player heads,
because Bedrock can't draw a Java player's skin on a head in a menu."""
import sys
from PIL import Image

ROWS = """
................
.....aaaaaa.....
....abbbbbba....
....acbbbbba....
....abbbbbba....
....aebbbbea....
.....aeeeea.....
......aaaa......
...aaabbbbaaa...
..abbbbbbbbbba..
.acbbbbbbbbbbba.
.abbbbbbbbbbbba.
.aeeeeeeeeeeeea.
.aeeeeeeeeeeeea.
..aaaaaaaaaaaa..
................
""".split()
COL = {"a": (26, 27, 38, 255), "b": (178, 102, 255, 255), "c": (214, 170, 255, 255), "e": (125, 63, 196, 255)}

im = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
for y, row in enumerate(ROWS):
    for x, ch in enumerate(row):
        if ch in COL:
            im.putpixel((x, y), COL[ch])
im.save(sys.argv[1] if len(sys.argv) > 1 else "player.png")
