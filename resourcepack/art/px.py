def flame_frames():
    """Little animated flames in the game's fire colours."""
    import random
    frames = []
    for f in range(8):
        r = random.Random(f * 7 + 3)
        img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
        cols = [hexc('#a8280c'), hexc('#ec5a14'), hexc('#ffa22a'), hexc('#ffe46a'), hexc('#fff8c8')]
        for x in range(3, 13):
            h = 6 + int(5 * (1 - abs(x - 7.5) / 5)) + r.randint(-2, 2)
            for y in range(16 - h, 16):
                d = (y - (16 - h)) / h
                core = 1 - abs(x - 7.5) / 5
                k = min(4, int(d * 2.2 + core * 2.4))
                img.putpixel((x, y), cols[k] + (255,))
        frames.append(img)
    return frames


