def hexc(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def shade(c, f):
    return tuple(max(0, min(255, round(v * f))) for v in c)


def mirror(boxes):
    """The same boxes on the other side (x flipped)."""
    return [(-b[3], b[1], b[2], -b[0], b[4], b[5], b[6]) for b in boxes]


