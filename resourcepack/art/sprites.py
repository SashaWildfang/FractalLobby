def hexc(h):
    h = h.lstrip('#')
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def draw(rows):
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(rows[:16]):
        for x, ch in enumerate(row[:16]):
            if ch in PAL:
                img.putpixel((x, y), hexc(PAL[ch]) + (255,))
    return img


def build(out_root):
    for path, rows in SPRITES.items():
        folder, name = path.split('/')
        for d in (f'textures/item/{folder}', f'models/item/{folder}', f'items/{folder}'):
            os.makedirs(f'{out_root}/assets/fractal/{d}', exist_ok=True)
        draw(rows).save(f'{out_root}/assets/fractal/textures/item/{path}.png')
        json.dump({"parent": "minecraft:item/generated", "textures": {"layer0": f"fractal:item/{path}"}},
                  open(f'{out_root}/assets/fractal/models/item/{path}.json', 'w'))
        json.dump({"model": {"type": "minecraft:model", "model": f"fractal:item/{path}"}},
                  open(f'{out_root}/assets/fractal/items/{path}.json', 'w'))
    # The disco ball for the gadget: a little mirrored cube on a string, turning in the air.
    tex = Image.new('RGBA', (16, 16), (0, 0, 0, 255))
    shades = [(235, 235, 245), (170, 175, 190), (120, 200, 255), (255, 255, 255), (200, 160, 255), (140, 140, 155)]
    for y in range(16):
        for x in range(16):
            tex.putpixel((x, y), shades[((x // 2) * 7 + (y // 2) * 3) % len(shades)] + (255,))
    tex.save(f'{out_root}/assets/fractal/textures/item/gadget/disco_ball_3d.png')
    faces = {d: {"uv": [0, 0, 16, 16], "texture": "#t"} for d in ('north', 'south', 'east', 'west', 'up', 'down')}
    string = {d: {"uv": [0, 0, 1, 1], "texture": "#t"} for d in ('north', 'south', 'east', 'west', 'up', 'down')}
    json.dump({"textures": {"t": "fractal:item/gadget/disco_ball_3d", "particle": "fractal:item/gadget/disco_ball_3d"},
               "elements": [{"from": [3, 3, 3], "to": [13, 13, 13], "faces": faces, "light_emission": 12},
                            {"from": [7.5, 13, 7.5], "to": [8.5, 24, 8.5], "faces": string}]},
              open(f'{out_root}/assets/fractal/models/item/gadget/disco_ball_3d.json', 'w'))
    json.dump({"model": {"type": "minecraft:model", "model": "fractal:item/gadget/disco_ball_3d"}},
              open(f'{out_root}/assets/fractal/items/gadget/disco_ball_3d.json', 'w'))
    return list(SPRITES)
